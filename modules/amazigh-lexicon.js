function norm(text) {
  return String(text || '').replace(/[’]/g, "'").trim().toLowerCase();
}

const LEXICON = new Map(
  ENTRIES.map(([fr, shi, tzm, rif, zgh]) => [norm(fr), { shi, tzm, rif, zgh }]),
);

export function amazighEntry(frText, code) {
  if (!['shi', 'tzm', 'rif', 'zgh'].includes(code)) return null;
  const hit = LEXICON.get(norm(frText));
  if (hit && hit[code]) return hit[code];
  const self = /^(.*)\(Moi\)\s*$/i.exec(String(frText || ''));
  if (self) {
    const me = LEXICON.get('moi')?.[code];
    if (me) {
      const prefix = self[1].trim();
      return {
        lat: prefix ? `${prefix} (${me.lat})` : me.lat,
        tif: prefix ? `${prefix} (${me.tif})` : me.tif,
      };
    }
  }
  return null;
}

export function hasAmazighWord(frText, code) {
  return Boolean(amazighEntry(frText, code));
}
